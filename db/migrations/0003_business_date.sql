-- 0003: business_date — تاريخ الفاتورة بتوقيت القاهرة
--
-- SQLite بيرجع date() بالـ UTC. المحل بيقفل بعد منتصف الليل، فكانت فواتير
-- 12 ص → 2 ص بتتحسب على اليوم السابق في التقارير. العمود ده بيتحسب بالتوقيت
-- المحلي وقت إنشاء الفاتورة، وكل التقارير بتفلتر عليه.
-- ============================================================================

ALTER TABLE orders ADD COLUMN business_date TEXT;

CREATE INDEX IF NOT EXISTS orders_business_date_idx ON orders(business_date, channel);

-- الفواتير القديمة: تقريب بفارق ساعتين (توقيت القاهرة الشتوي).
-- فرق ساعة واحد ممكن يحصل في الفواتير القديمة اللي بين 11 مساءً و2 صباحًا
-- أيام التوقيت الصيفي — التاريخ ده تقريبي ومحدش بيتأثر بيه دلوقتي.
UPDATE orders
   SET business_date = date(created_at, '+2 hours')
 WHERE business_date IS NULL;
