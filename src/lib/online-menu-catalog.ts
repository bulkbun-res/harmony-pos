/**
 * تحديد صورة الخبز التفاعلية لساندوتش معين بناءً على نوع الخبز المختار
 */
export function getInteractiveSandwichImage(itemId: string, selectedModifierNameOrId?: string): string | null {
  const sandwich = SANDWICH_IMAGES_MAP[itemId];
  if (!sandwich) return null;

  if (!selectedModifierNameOrId) {
    return sandwich.defaultHero;
  }

  const s = selectedModifierNameOrId.toLowerCase();
  if (s.includes("تورتيلا") || s.includes("tortilla") || s.includes("br-tortilla")) {
    return sandwich.tortilla;
  }
  if (s.includes("سن") || s.includes("brown") || s.includes("br-brown")) {
    return sandwich.brown;
  }
  if (s.includes("قمح") || s.includes("wheat") || s.includes("br-wheat")) {
    return sandwich.wheat;
  }
  if (s.includes("فرنسي") || s.includes("french") || s.includes("br-french")) {
    return sandwich.french;
  }

  return sandwich.defaultHero;
}

/**
 * يرجع الصورة المناسبة لأي صنف في المنيو الإلكتروني
 */
export function resolveOnlineItemImage(
  item: { id: string; groupId: string; image?: string },
  selectedModifier?: string,
): string {
  // 1. إذا كان ساندوتش
  const swImg = getInteractiveSandwichImage(item.id, selectedModifier);
  if (swImg) return swImg;

  // 2. إذا كان صنف آخر مسجل في المكتبة
  if (OTHER_ITEMS_MAP[item.id]) {
    return OTHER_ITEMS_MAP[item.id];
  }

  // 3. رابط خارجي مباشر لو كان موجوداً
  if (item.image?.startsWith("http://") || item.image?.startsWith("https://")) {
    return item.image;
  }

  // 4. صورة عامة كحل أخير
  return hmFrench;
}
